export const DICTS: Record<Lang, Dict> = { bn, en };

export const DEFAULT_LANG: Lang = "bn";

export function isLang(value: unknown): value is Lang {
  return value === "bn" || value === "en";
}

/** Translate `key`, interpolating `{var}` placeholders. Missing keys fall back to key. */
export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? DICTS.bn;
  let value = dict[key] ?? DICTS.bn[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export function hasKey(lang: Lang, key: string): boolean {
  return key in (DICTS[lang] ?? {});
}

export function dictKeys(lang: Lang): string[] {
  return Object.keys(DICTS[lang] ?? {}).sort();
}

/** Browser language preference (Bangla is always the default). */
export function readStoredLang(): Lang {
  try {
    if (typeof localStorage === "undefined") return DEFAULT_LANG;
    const value = localStorage.getItem("chanasta.lang");
    return isLang(value) ? value : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

export function storeLang(lang: Lang): void {
  try {
    if (typeof localStorage !== "undefined") localStorage.setItem("chanasta.lang", lang);
  } catch {
    /* storage can be unavailable (private mode); language still works this page */
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = lang;
  }
}

/** Apply `<html lang>` and the language-aware CSS leading tokens. */
export function applyLang(lang: Lang): void {
  if (typeof document !== "undefined") {
    document.documentElement.lang = lang;
  }
}
