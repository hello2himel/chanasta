#!/usr/bin/env node
/**
 * Vendor the deshiQR engine (Bangla QR payload logic + QR encoder) into `vendor/deshiqr/`.
 *
 * deshiQR is the developer-facing engine: https://github.com/hello2himel/deshiQR.
 * Chanasta is a product built on it. We vendor a pinned copy instead of depending on
 * unpublished npm packages, so this repo builds anywhere (CI, Netlify, Pages) with no
 * registry access and no cross-repo install steps.
 *
 * Source resolution:
 *   1. DESHIQR_SOURCE env var (path to a deshiQR checkout)
 *   2. ../deshiQR (sibling checkout, used in development)
 *   3. a shallow git clone of https://github.com/hello2himel/deshiQR (DESHIQR_REF, default main)
 *
 * The generated files are committed. Re-run this script after upgrading deshiQR and commit
 * the result; `VENDOR.json` records exactly which commit the copy came from.
 *
 * Do not edit files under vendor/deshiqr by hand.
 */
import { execFileSync } from "node:child_process";
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const vendorDir = join(root, "vendor/deshiqr");
const repoUrl = "https://github.com/hello2himel/deshiQR.git";
const ref = process.env.DESHIQR_REF ?? "main";

function git(args, cwd) {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

async function resolveSource() {
  const candidates = [process.env.DESHIQR_SOURCE, join(root, "..", "deshiQR")].filter(Boolean);
  for (const candidate of candidates) {
    if (existsSync(join(candidate, "packages/core/src/index.ts"))) {
      let commit = "unknown";
      try {
        commit = git(["rev-parse", "HEAD"], candidate);
      } catch {
        // not a git checkout; still usable
      }
      return { dir: candidate, commit, source: "local" };
    }
  }

  const tmp = await mkdtemp(join(tmpdir(), "deshiqr-src-"));
  git(["clone", "--depth", "1", "--branch", ref, repoUrl, tmp]);
  return { dir: tmp, commit: git(["rev-parse", "HEAD"], tmp), source: "git", cleanup: tmp };
}

const { dir: sourceDir, commit, source, cleanup } = await resolveSource();

const packages = [
  { name: "core", from: join(sourceDir, "packages/core/src"), to: join(vendorDir, "core/src") },
  { name: "qr", from: join(sourceDir, "packages/qr/src"), to: join(vendorDir, "qr/src") },
];

await rm(vendorDir, { recursive: true, force: true });
await mkdir(vendorDir, { recursive: true });

for (const pkg of packages) {
  await mkdir(pkg.to, { recursive: true });
  await cp(pkg.from, pkg.to, {
    recursive: true,
    filter: (path) => !path.includes("node_modules") && !path.endsWith(".map"),
  });
}

const license = await readFile(join(sourceDir, "LICENSE"), "utf8");
await writeFile(join(vendorDir, "LICENSE"), license, "utf8");

const version = JSON.parse(await readFile(join(sourceDir, "packages/core/package.json"), "utf8")).version;
const manifest = {
  engine: "deshiQR",
  description: "Bangla QR (NPSB) payload engine and QR encoder, vendored into Chanasta.",
  repository: "https://github.com/hello2himel/deshiQR",
  version,
  ref,
  commit,
  resolvedFrom: source,
  packages: ["core (deshiqr)", "qr (deshiqr-qr)"],
  license: "MIT",
  note: "Generated by scripts/sync-deshiqr.mjs. Do not edit these files by hand.",
  syncedAt: new Date().toISOString(),
};
await writeFile(join(vendorDir, "VENDOR.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");

await writeFile(
  join(vendorDir, "NOTICE.md"),
  `# Vendored deshiQR engine

The TypeScript files under this directory are copied, unmodified, from **deshiQR** —
the developer-facing Bangla QR payload library and QR encoder:
<https://github.com/hello2himel/deshiQR>.

- Source version: ${version}
- Source commit: ${commit}
- License: MIT (see \`LICENSE\` in this directory and the project LICENSE)
- Re-sync with: \`pnpm sync:deshiqr\` (or \`node scripts/sync-deshiqr.mjs\`)

Do not edit these files by hand. Changes belong in the deshiQR repository; re-sync afterwards.
`,
  "utf8",
);

if (cleanup) await rm(cleanup, { recursive: true, force: true });

console.log(`vendored deshiQR ${version} @ ${commit.slice(0, 10)} (${source})`);
for (const pkg of packages) console.log(`  ${relative(root, pkg.to)}`);
